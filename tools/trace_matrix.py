"""Requirement → test traceability matrix (SRS NFR-QUAL-02).

Scans tests for ``@pytest.mark.req("ID", ...)`` and source code for requirement IDs in docstrings/
comments, then writes docs/traceability.md. ``--check`` exits non-zero if a requirement listed in
REQUIRED_P01 has no test.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQ_ID = re.compile(r"\b(?:ANA|CFG|ARC|DATA|NET|SCO|SEQ|SAF|PSU|AFG|GUI|REP|DIO|TMP|SIM|NFR-[A-Z]+)-\d{2}\b")
MARK = re.compile(r"@pytest\.mark\.req\(([^)]*)\)\s*(?:@[^\n]*\n\s*)*def (test_\w+)")

#: requirements that Phase 0–1 must cover with at least one test
REQUIRED_P01 = [
    "ARC-05", "CFG-01", "CFG-02", "CFG-03", "CFG-05", "CFG-07", "DATA-04", "NET-06",
    "ANA-03", "ANA-05", "ANA-07", "ANA-08", "ANA-09", "ANA-11", "ANA-12", "ANA-14", "ANA-15", "ANA-16",
    "ANA-17", "ANA-18", "ANA-19", "ANA-21", "ANA-22", "ANA-23", "ANA-24", "ANA-27", "ANA-30", "ANA-41",
    "ANA-42",
]


def collect() -> tuple[dict[str, list[str]], dict[str, set[str]]]:
    tests: dict[str, list[str]] = defaultdict(list)
    for f in sorted((ROOT / "tests").rglob("test_*.py")):
        text = f.read_text(encoding="utf-8")
        for args, name in MARK.findall(text):
            for rid in re.findall(r'"([^"]+)"', args):
                tests[rid].append(f"{f.relative_to(ROOT).as_posix()}::{name}")
    code: dict[str, set[str]] = defaultdict(set)
    for f in sorted((ROOT / "autodpt").rglob("*.py")):
        for rid in set(REQ_ID.findall(f.read_text(encoding="utf-8"))):
            code[rid].add(f.relative_to(ROOT).as_posix())
    return tests, code


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    tests, code = collect()
    ids = sorted(set(tests) | set(code), key=lambda s: (s.split("-")[0], s))
    lines = ["# Traceability matrix (generated by tools/trace_matrix.py)", "",
             "| Requirement | Implemented in | Verified by |", "|---|---|---|"]
    for rid in ids:
        impl = "<br>".join(sorted(code.get(rid, []))) or "-"
        ver = "<br>".join(tests.get(rid, [])) or "-"
        lines.append(f"| {rid} | {impl} | {ver} |")
    (ROOT / "docs" / "traceability.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = [r for r in REQUIRED_P01 if r not in tests]
    print(f"{len(ids)} requirement IDs traced; {sum(len(v) for v in tests.values())} test links")
    if missing:
        print("requirements without a test:", ", ".join(missing))
        return 1 if args.check else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
