"""Regenerate docs/analysis_accuracy.md: analysis error vs synthetic ground truth (ANA-42).

    python tools/accuracy_report.py [--seeds 10]
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from autodpt.analysis import synth  # noqa: E402
from autodpt.analysis.analyse import analyse_shot  # noqa: E402
from autodpt.analysis.preprocess import waveforms_from_raw  # noqa: E402
from autodpt.config.models import AnalysisConfig  # noqa: E402
from autodpt.config.presets import load_preset  # noqa: E402
from tests.conftest import NOISE, true_shot  # noqa: E402

TIMES = {"td_on", "t_r", "td_off", "t_f", "t_z", "t_rr", "t_a", "t_b"}
KEYS = ["e_on", "e_off", "e_rec", "td_on", "t_r", "td_off", "t_f", "t_z", "t_rr", "t_a", "t_b", "q_rr",
        "i_rrm", "softness", "didt_on", "dvdt_on", "dvdt_off", "didt_off", "i_off", "i_on", "vdc_off",
        "vce_peak_off", "overshoot_dv", "l_sigma_on"]
CASES = [("igbt", "IEC60747-9"), ("sic", "IEC60747-8")]


def err(key: str, a: float, b: float) -> float:
    if key in TIMES:
        return abs(a - b) * 1e9
    return abs(a / b - 1) * 100 if b else abs(a - b)


def run(seeds: int) -> str:
    cfg = AnalysisConfig()
    cols: dict[str, dict[str, tuple[float, float, float]]] = {}
    truths: dict[str, dict[str, float]] = {}
    for case, preset in CASES:
        ts = true_shot(case)
        p = load_preset(preset)
        tr = synth.truth(ts, p, cfg)
        truths[case] = tr
        raw, dt, t0 = synth.acquire(ts, synth.SynthAcq(bits=16))
        ideal = analyse_shot(waveforms_from_raw(raw, dt, t0), synth.meta_for(ts), cfg, p).values["none"]
        worst: dict[str, float] = {}
        for s in range(seeds):
            raw, dt, t0 = synth.acquire(ts, synth.SynthAcq(bits=12, noise_rms=NOISE[case], seed=s))
            v = analyse_shot(waveforms_from_raw(raw, dt, t0), synth.meta_for(ts), cfg, p).values["none"]
            for k in KEYS:
                if k in tr:
                    worst[k] = max(worst.get(k, 0.0), err(k, v.get(k, math.nan), tr[k]))
        cols[case] = {k: (tr[k], err(k, ideal.get(k, math.nan), tr[k]), worst[k]) for k in KEYS if k in tr}

    out = ["# Analysis accuracy vs. synthetic ground truth", "",
           "Generated by `tools/accuracy_report.py` (SRS ANA-41/42). Error = |measured − truth|: "
           "**ns** for times, **%** otherwise.", "",
           "* **Ideal**: no noise, 16-bit, 10 GS/s — algorithm error only (ANA-42 limits).",
           f"* **Realistic**: 12-bit, 10 GS/s, noise 0.5 % of the V_CE/I_C swing and 0.1 V on gates; "
           f"worst of {seeds} seeds.", "",
           "Synthetic devices: IGBT-like 400 V / 200 A, L_σ 25 nH, I_rrm 120 A, 300 ns tail (preset "
           "IEC60747-9); SiC-like 600 V / 300 A, L_σ 15 nH, I_rrm 30 A, ringing (preset IEC60747-8).", "",
           "| parameter | IGBT truth | IGBT ideal | IGBT realistic | SiC truth | SiC ideal | SiC realistic |",
           "|---|---|---|---|---|---|---|"]

    def fmt_truth(k: str, v: float) -> str:
        if k in TIMES:
            return f"{v * 1e9:.1f} ns"
        if k.startswith("e_"):
            return f"{v * 1e3:.3f} mJ"
        if k == "q_rr":
            return f"{v * 1e9:.0f} nC"
        if k == "l_sigma_on":
            return f"{v * 1e9:.1f} nH"
        if k.startswith(("didt", "dvdt")):
            return f"{v * 1e-9:.2f} /ns"
        return f"{v:.4g}"

    for k in KEYS:
        row = [k]
        for case, _ in CASES:
            if k in cols[case]:
                t, ei, er = cols[case][k]
                u = " ns" if k in TIMES else " %"
                row += [fmt_truth(k, t), f"{ei:.3f}{u}", f"{er:.2f}{u}"]
            else:
                row += ["-", "-", "-"]
        out.append("| " + " | ".join(row) + " |")
    out += ["", "## Reading the realistic column", "",
            "* Energies (E_on, E_off) and switching times are robust: < 2 % / ≈ 1–2 ns with 0.5 % noise.",
            "* **IGBT t_f, t_z, di/dt_off** use the 10 %/2 % current levels, which lie on the slow tail "
            "current (≈ 0.07 A/ns): 1 A of noise moves the crossing by ~15 ns. Inherent to the definition; "
            "average repetitions (ANA-26) or apply a mild low-pass (ANA-03) for these.",
            "* **SiC I_rrm, Q_rr, E_rec, S**: I_rrm is only 10 % of the current-channel range, so noise "
            "biases the peak (max-of-noise). Average repetitions, or measure the diode current on a "
            "lower-range probe.",
            "* **Overshoot ΔV** (and absolute peaks) are biased upward by noise (a maximum of a noisy "
            "signal); this also applies to the scope's own max measurements.",
            "* De-skew matters more than noise: an uncorrected 4.7 ns current-probe skew changes SiC E_on by "
            "−14 % and E_off by +16 % (run `python -m autodpt --sim --device sic --skew 4.7`)."]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=10)
    text = run(ap.parse_args().seeds)
    (ROOT / "docs" / "analysis_accuracy.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
